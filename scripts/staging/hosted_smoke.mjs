function parseEnvFile(path) {
  const out = {}
  for (const raw of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith('#')) continue
    const i = line.indexOf('=')
    if (i < 1) continue
    out[line.slice(0, i).trim()] = line.slice(i + 1).trim().replace(/^["']|["']$/g, '')
  }
  return out
}

function loadStaging() {
  if (!existsSync(ENV_FILE)) throw new Error('.env.staging not found')
  const env = parseEnvFile(ENV_FILE)
  const url = (env.STAGING_SUPABASE_URL ?? '').replace(/\/+$/, '')
  const anon = env.STAGING_SUPABASE_ANON_KEY ?? ''
  if (!url || !anon) throw new Error('STAGING_SUPABASE_URL / STAGING_SUPABASE_ANON_KEY missing in .env.staging')
  let host = ''
  try {
    host = new URL(url).hostname
  } catch {
    /* handled below */
  }
  if (!url.includes(REF) || host !== `${REF}.supabase.co`) {
    throw new Error(`refusing to run: STAGING_SUPABASE_URL is not the staging project ${REF}`)
  }
  return { url, anon }
}

