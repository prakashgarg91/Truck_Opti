const cmd = process.argv[2]
try {
  if (cmd === 'prepare') prepare()
  else if (cmd === 'run') await run()
  else {
    console.error('usage: node scripts/staging/hosted_smoke.mjs prepare|run')
    process.exit(2)
  }
} catch (e) {
  console.error(`hosted_smoke: ${String(e?.message ?? e)}`)
  process.exit(2)
}
