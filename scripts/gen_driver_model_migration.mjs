#!/usr/bin/env node
/**
 * Generator for supabase/migrations/20261013000000_driver_model_authority.sql
 * (TO-143-D3 driver model, owner decision 2026-11-04 + Opus advice).
 *
 * agency_driver_employment becomes the single driver-to-agency authority;
 * agency_trucks.driver_id is only a default truck-driver pairing. Reservations
 * project onto agency_jobs.truck_id/driver_id. Function bodies are extracted
 * from the CURRENT text of the migration that last defined them and patched at
 * asserted anchors, so nothing is retyped.
 *
 * Usage: node scripts/gen_driver_model_migration.mjs          writes the migration
 *        node scripts/gen_driver_model_migration.mjs --check  exit 1 on drift
 * STAFF env override for previews: DRIVER_MODEL_OUT=/tmp/x.sql
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const DIR = resolve(here, '..', 'supabase', 'migrations')
const OUT_NAME = '20261013000000_driver_model_authority.sql'
const OUT = join(DIR, OUT_NAME)

const sources = readdirSync(DIR)
  .filter((f) => f.endsWith('.sql') && f < OUT_NAME)
  .sort()
  .map((f) => ({ file: f, text: readFileSync(join(DIR, f), 'utf8').replace(/\r\n/g, '\n') }))

/** Latest definition of `public.<name>(`; end is `$$;` or `$$ LANGUAGE plpgsql;`. */
function extract(name) {
  const header = new RegExp(String.raw`CREATE OR REPLACE FUNCTION public\.${name}\(`)
  let found = null
  for (const s of sources) {
    const m = header.exec(s.text)
    if (!m) continue
    const rest = s.text.slice(m.index)
    const tag = /AS\s+(\$[A-Za-z0-9_]*\$)/.exec(rest)
    if (!tag) throw new Error(`no body tag for ${name}`)
    const from = tag.index + tag[0].length
    const a = rest.indexOf(`${tag[1]};`, from)
    const b = rest.indexOf(`${tag[1]} LANGUAGE plpgsql;`, from)
    const useB = b >= 0 && (a < 0 || b < a)
    const end = useB ? b + `${tag[1]} LANGUAGE plpgsql;`.length : a + tag[1].length + 1
    if (end <= from) throw new Error(`no body end for ${name}`)
    found = { file: s.file, sql: rest.slice(0, end) }
  }
  if (!found) throw new Error(`function not found: ${name}`)
  return found
}

function patch(name, edits) {
  const { file, sql } = extract(name)
  let out = sql
  for (const { anchor, insertBefore, insertAfter, replaceWith } of edits) {
    const count = out.split(anchor).length - 1
    if (count !== 1) throw new Error(`${name} (${file}): anchor must match exactly once, found ${count}: ${JSON.stringify(anchor.slice(0, 70))}`)
    if (replaceWith !== undefined) out = out.replace(anchor, replaceWith)
    else out = insertBefore ? out.replace(anchor, insertBefore + anchor) : out.replace(anchor, anchor + insertAfter)
  }
  return `-- ${name} (from ${file}, patched)\n${out}\n`
}

const HEAD = `-- TO-143-D3 driver model: agency_driver_employment is the single authority.
--
-- GENERATED by scripts/gen_driver_model_migration.mjs. Owner decision
-- 2026-11-04 (advisor-recommended):
--   1. Backfill an ACTIVE employment row for every approved driver already
--      linked through agency_trucks.driver_id. Hard cases STOP the migration
--      with a listing (driver employed by another agency, driver not approved);
--      nothing is invented and nothing is partially written.
--   2. driver_is_assigned_to_agency() now means "active employment in that
--      agency"; the agency_jobs and agency_pay payout guards switch together.
--   3. agency_trucks.driver_id stays only as a default truck-driver pairing and
--      may be set only for an actively employed driver; ending employment
--      clears it.
--   4. reserve_fleet_assignment projects onto agency_jobs.truck_id/driver_id;
--      release / offer decline|expire|cancel clear them only while they still
--      match the reservation; a consumed reservation keeps them.
--   5. agency_driver_employment_end refuses with driver_has_active_assignment
--      while the employment holds an active reservation.

-- ---------------------------------------------------------------------------
-- 1. Backfill (stop-and-list on conflicts)
-- ---------------------------------------------------------------------------
DO $backfill$
DECLARE
  v_blocked text;
BEGIN
  SELECT string_agg(
           format('%s (agency %s, %s)', c.driver_id, c.agency_id, c.reason),
           '; ' ORDER BY c.driver_id)
    INTO v_blocked
  FROM (
    SELECT DISTINCT t.driver_id, t.agency_id,
           CASE
             WHEN NOT public.driver_is_approved_for_assignment(t.driver_id) THEN 'driver not approved'
             ELSE 'driver actively employed by another agency'
           END AS reason
    FROM public.agency_trucks t
    WHERE t.driver_id IS NOT NULL
      AND NOT EXISTS (
        SELECT 1 FROM public.agency_driver_employment e
        WHERE e.driver_id = t.driver_id AND e.agency_id = t.agency_id AND e.status = 'active'
      )
      AND (
        NOT public.driver_is_approved_for_assignment(t.driver_id)
        OR EXISTS (
          SELECT 1 FROM public.agency_driver_employment e2
          WHERE e2.driver_id = t.driver_id AND e2.agency_id <> t.agency_id AND e2.status = 'active'
        )
      )
  ) c;

  IF v_blocked IS NOT NULL THEN
    RAISE EXCEPTION 'Driver model backfill blocked: %', v_blocked;
  END IF;

  INSERT INTO public.agency_driver_employment (agency_id, driver_id, status)
  SELECT DISTINCT ON (t.driver_id) t.agency_id, t.driver_id, 'active'
  FROM public.agency_trucks t
  WHERE t.driver_id IS NOT NULL
    AND NOT EXISTS (
      SELECT 1 FROM public.agency_driver_employment e
      WHERE e.driver_id = t.driver_id AND e.status = 'active'
    )
  ORDER BY t.driver_id, t.created_at;
END
$backfill$;

-- ---------------------------------------------------------------------------
-- 2. Authority guard: employment replaces the truck link
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.driver_is_assigned_to_agency(p_driver_id uuid, p_agency_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.agency_driver_employment e
    WHERE e.driver_id = p_driver_id
      AND e.agency_id = p_agency_id
      AND e.status = 'active'
  );
$$;

-- ---------------------------------------------------------------------------
-- 3-5. Patched functions
-- ---------------------------------------------------------------------------
`

